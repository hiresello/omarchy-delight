#!/bin/bash

# Integration with user-owned Omarchy files. Everything Delight adds is
# generated from installed modules and lives inside marked blocks or Delight-
# named files, so it can be regenerated or removed at any time.

DELIGHT_HYPR_USER="$HOME/.config/hypr/hyprland.lua"
DELIGHT_HYPR_GENERATED="$DELIGHT_CONFIG_DIR/hypr.lua"
DELIGHT_MENU_FILE="$HOME/.config/omarchy/extensions/omarchy-menu.jsonc"
DELIGHT_THEME_HOOK="$HOME/.config/omarchy/hooks/theme-set.d/50-omarchy-delight"
DELIGHT_CONTROL_CENTER="delight.control-center"

delight_installed_modules() {
  local id
  while IFS= read -r id; do
    if delight_is_installed "$id"; then
      printf '%s\n' "$id"
    fi
  done < <(delight_modules)
}

delight_hypr_generate() {
  local id file
  printf '%s\n' "-- Generated by omarchy-delight. Do not edit; regenerate with 'delight refresh'."
  while IFS= read -r id; do
    file="$DELIGHT_MODULES_DIR/$id/hypr.lua"
    if [[ -f $file ]]; then
      printf 'pcall(dofile, "%s")\n' "$DELIGHT_HOME_DIR/modules/$id/hypr.lua"
    fi
  done < <(delight_installed_modules)
}

delight_menu_generate() {
  local id
  printf '  "delight": {"icon":"󰀵","label":"Delight","description":"Omarchy Delight"},\n'
  printf '  "delight.control-center": {"icon":"󰒓","label":"Control Center","action":"delight ui summon %s"},\n' "$DELIGHT_CONTROL_CENTER"
  while IFS= read -r id; do
    jq -r --arg id "$id" '.menu[]? |
      "  \(("delight." + $id + "." + .id) | tojson): \({icon, label, action} | with_entries(select(.value != null)) | tojson),"' \
      "$DELIGHT_MODULES_DIR/$id/module.json"
  done < <(delight_installed_modules)
}

delight_theme_hook_body() {
  cat <<'HOOK'
#!/bin/bash
# Installed by omarchy-delight; removed by its uninstall.sh.
[[ -x $HOME/.local/bin/delight ]] && exec "$HOME/.local/bin/delight" hook theme-set "$@"
exit 0
HOOK
}

# Regenerate every touchpoint from the current set of installed modules.
delight_touchpoints_sync() {
  delight_is_installed core || return 0
  delight_hypr_generate | delight_write "$DELIGHT_HYPR_GENERATED"
  delight_block_set_end "$DELIGHT_HYPR_USER" "--" \
    "pcall(dofile, os.getenv(\"HOME\") .. \"/.config/omarchy-delight/hypr.lua\")"
  delight_block_set_jsonc "$DELIGHT_MENU_FILE" "$(delight_menu_generate)"
  delight_theme_hook_body | delight_write "$DELIGHT_THEME_HOOK" 755
}

delight_touchpoints_remove() {
  delight_block_remove "$DELIGHT_HYPR_USER"
  delight_block_remove "$DELIGHT_MENU_FILE"
  delight_rm "$DELIGHT_HYPR_GENERATED"
  delight_rm "$DELIGHT_THEME_HOOK"
  delight_rmdir_empty "$(dirname -- "$DELIGHT_THEME_HOOK")"
}
