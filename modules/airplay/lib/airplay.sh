#!/bin/bash

airplay_conf_path() {
  printf '%s/airplay/shairport-sync.conf\n' "$DELIGHT_CONFIG_DIR"
}

airplay_runtime_dir() {
  printf '%s/airplay\n' "$DELIGHT_RUNTIME_DIR"
}

airplay_fifo_path() {
  printf '%s/metadata\n' "$(airplay_runtime_dir)"
}

airplay_now_playing_path() {
  printf '%s/now-playing.json\n' "$(airplay_runtime_dir)"
}

airplay_name() {
  local name pretty
  name=$(delight_config_get airplay name 2>/dev/null) || name=""
  if [[ -z $name ]]; then
    pretty=$(hostnamectl --pretty 2>/dev/null) || pretty=""
    name=$pretty
  fi
  if [[ -z $name && -r /etc/machine-info ]]; then
    name=$(sed -n 's/^PRETTY_HOSTNAME=//p' /etc/machine-info | head -n 1)
    name=${name#\"}
    name=${name%\"}
    name=${name#\'}
    name=${name%\'}
  fi
  [[ -n $name ]] || name=$(uname -n)
  printf '%s\n' "${name:0:50}"
}

airplay_conf_render() {
  local name pipe escaped_name escaped_pipe
  name="$1"
  pipe="$2"
  escaped_name=$(printf '%s' "$name" | sed 's/\\/\\\\/g; s/"/\\"/g')
  escaped_pipe=$(printf '%s' "$pipe" | sed 's/\\/\\\\/g; s/"/\\"/g')
  cat <<EOF
// Generated by omarchy-delight (modules/airplay). Do not edit;
// change the name with: delight airplay rename <name>
general =
{
  name = "$escaped_name";
  output_backend = "pipewire";
  mdns_backend = "avahi";
  port = 7000;
  dbus_service_bus = "session";
  mpris_service_bus = "session";
};

sessioncontrol =
{
  allow_session_interruption = "yes";
};

pipewire =
{
  application_name = "AirPlay";
  node_name = "AirPlay";
};

metadata =
{
  enabled = "yes";
  include_cover_art = "no";
  cover_art_cache_directory = "";
  pipe_name = "$escaped_pipe";
  pipe_timeout = 5000;
};

diagnostics =
{
  log_output_to = "stderr";
};
EOF
}

airplay_write_conf() {
  local tmp
  tmp=$(mktemp)
  airplay_conf_render "$(airplay_name)" "$(airplay_fifo_path)" >"$tmp"
  delight_file_install airplay "$tmp" "$(airplay_conf_path)"
  rm -f -- "$tmp"
}

airplay_meta_empty() {
  printf '%s\n' '{"sender":"","ip":"","agent":"","title":"","artist":"","album":"","playing":false,"notified":false}'
}

airplay_meta_load() {
  local file
  file=$(airplay_now_playing_path)
  if [[ -f $file ]] && jq -e 'type == "object"' "$file" >/dev/null 2>&1; then
    AIRPLAY_META_STATE=$(jq -c '{sender:(.sender // ""),ip:(.ip // ""),agent:(.agent // ""),title:(.title // ""),artist:(.artist // ""),album:(.album // ""),playing:(.playing // false),notified:(.notified // false)}' "$file")
  else
    AIRPLAY_META_STATE=$(airplay_meta_empty)
  fi
  AIRPLAY_META_SAVED=$(jq -cS . <<<"$AIRPLAY_META_STATE")
}

airplay_meta_change() {
  local key="$1" value="$2"
  AIRPLAY_META_STATE=$(jq -c --arg key "$key" --arg value "$value" '.[$key] = $value' <<<"$AIRPLAY_META_STATE")
}

airplay_meta_notify_if_ready() {
  local ready sender ip source body
  ready=$(jq -r '.playing and (.sender != "" or .ip != "") and (.notified | not)' <<<"$AIRPLAY_META_STATE")
  if [[ $ready == "true" ]]; then
    sender=$(jq -r '.sender' <<<"$AIRPLAY_META_STATE")
    ip=$(jq -r '.ip' <<<"$AIRPLAY_META_STATE")
    source=$sender
    if [[ -z $source ]]; then
      source=$ip
    fi
    body="Playing on $(airplay_name)"
    delight_notify airplay "AirPlay started from $source" "$body"
    AIRPLAY_META_STATE=$(jq -c '.notified = true' <<<"$AIRPLAY_META_STATE")
  fi
}

airplay_meta_commit() {
  local state file
  state=$(jq -cS . <<<"$AIRPLAY_META_STATE")
  [[ $state != "$AIRPLAY_META_SAVED" ]] || return 0
  file=$(airplay_now_playing_path)
  printf '%s\n' "$state" | delight_write "$file" 600
  AIRPLAY_META_SAVED=$state
  delight_module_publish
}

airplay_meta_reset() {
  AIRPLAY_META_STATE=$(airplay_meta_empty)
}

airplay_meta_process_item() {
  local item="$1" type code value
  type=$(sed -n 's/.*<type>\([^<]*\)<\/type>.*/\1/p' <<<"$item" | head -n 1)
  code=$(sed -n 's/.*<code>\([^<]*\)<\/code>.*/\1/p' <<<"$item" | head -n 1)
  case "$type:$code" in
    636f7265:6d696e6d | 636f7265:61736172 | 636f7265:6173616c | 73736e63:736e616d | 73736e63:736e7561 | 73736e63:636c6970)
      value=$(sed -n '/<data encoding="base64">/,/<\/data>/p' <<<"$item" \
        | sed 's/.*<data encoding="base64">//;s#</data>.*##' \
        | tr -d '[:space:]' \
        | base64 -d 2>/dev/null) || value=""
      case "$type:$code" in
        636f7265:6d696e6d) airplay_meta_change title "$value" ;;
        636f7265:61736172) airplay_meta_change artist "$value" ;;
        636f7265:6173616c) airplay_meta_change album "$value" ;;
        73736e63:736e616d)
          airplay_meta_change sender "$value"
          airplay_meta_notify_if_ready
          airplay_meta_commit
          ;;
        73736e63:736e7561) airplay_meta_change agent "$value" ;;
        73736e63:636c6970) airplay_meta_change ip "$value" ;;
      esac
      ;;
    73736e63:70626567)
      AIRPLAY_META_STATE=$(jq -c '.playing = true' <<<"$AIRPLAY_META_STATE")
      airplay_meta_notify_if_ready
      airplay_meta_commit
      ;;
    73736e63:70656e64 | 73736e63:64697363)
      airplay_meta_reset
      airplay_meta_commit
      ;;
    73736e63:6d64656e)
      airplay_meta_notify_if_ready
      airplay_meta_commit
      ;;
  esac
}

airplay_metadata_parse() {
  local line buffer="" item
  airplay_meta_load
  while IFS= read -r line || [[ -n $line ]]; do
    buffer+="$line"$'\n'
    while [[ $buffer == *'</item>'* ]]; do
      item="${buffer%%</item>*}</item>"
      buffer=${buffer#*'</item>'}
      airplay_meta_process_item "$item"
    done
  done
}

airplay_slug() {
  local slug
  slug=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-|-$//g')
  if [[ -z $slug ]]; then
    slug=device
  fi
  printf '%s\n' "$slug"
}

airplay_devices_json() {
  local state sender agent kind
  state=$(airplay_read_now_playing)
  sender=$(jq -r '.sender // ""' <<<"$state")
  agent=$(jq -r '.agent // ""' <<<"$state")
  if [[ $(jq -r '.playing // false' <<<"$state") != "true" || -z $sender ]]; then
    printf '[]\n'
    return 0
  fi
  if [[ $sender == *iPhone* || $agent == *iPhone* ]]; then
    kind=phone
  elif [[ $sender == *iPad* || $agent == *iPad* ]]; then
    kind=tablet
  else
    kind=computer
  fi
  jq -cn --arg id "airplay:$(airplay_slug "$sender")" --arg name "$sender" --arg kind "$kind" \
    '[{id:$id,name:$name,kind:$kind,transport:"airplay",connected:true}]'
}

airplay_read_now_playing() {
  local file
  file=$(airplay_now_playing_path)
  if [[ -f $file ]] && jq -e 'type == "object"' "$file" >/dev/null 2>&1; then
    jq -c . "$file"
  else
    airplay_meta_empty
  fi
}
