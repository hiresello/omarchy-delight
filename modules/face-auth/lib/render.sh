#!/bin/bash

# Render the face-auth PAM stack, gate, stamp, sleep hook, and rollback script.
# Outputs are byte-stable for a given policy. Paths are the real system paths;
# FACE_AUTH_ROOT is a prefix the scripts honour so tests never touch the host.

face_auth_pam_row() {
  printf '%-7s %-31s %s\n' "$1" "$2" "$3"
}

face_auth_faillock_args() {
  local action="$1" deny="$2" interval="$3" unlock="$4"
  printf '%s silent deny=%s fail_interval=%s unlock_time=%s' "$action" "$deny" "$interval" "$unlock"
}

# Auth stack for one service. The shape is what pamcheck.sh accepts.
face_auth_render_pam() {
  local service="$1" policy="$2"
  local deny interval unlock fail_args
  deny=$(jq -r '.deny' <<<"$policy")
  interval=$(jq -r '.fail_interval' <<<"$policy")
  unlock=$(jq -r '.unlock_time' <<<"$policy")
  fail_args=$(face_auth_faillock_args preauth "$deny" "$interval" "$unlock")
  cat <<EOF
#%PAM-1.0
# Generated by omarchy-delight face-auth. Do not edit.
# Service: ${service}
# Face runs only when face-auth-gate exits 0. Any other result skips it.
# A face match does not refresh the password stamp. A face miss still asks
# for the password. Rollback: sudo /usr/local/sbin/delight-face-auth-disable
EOF
  face_auth_pam_row auth "[success=ok default=die]" "pam_faillock.so ${fail_args}"
  face_auth_pam_row auth "[success=ignore default=2]" "pam_exec.so quiet /usr/local/lib/omarchy-delight/face-auth-gate ${service}"
  face_auth_pam_row auth "[success=4 default=ignore]" "pam_howdy.so"
  fail_args=$(face_auth_faillock_args authfail "$deny" "$interval" "$unlock")
  face_auth_pam_row auth "[default=ignore]" "pam_faillock.so ${fail_args}"
  face_auth_pam_row auth "[success=1 default=bad]" "pam_unix.so try_first_pass"
  face_auth_pam_row auth "[default=die]" "pam_faillock.so ${fail_args}"
  face_auth_pam_row auth "[default=ignore]" "pam_exec.so quiet /usr/local/lib/omarchy-delight/face-auth-stamp ${service}"
  fail_args=$(face_auth_faillock_args authsucc "$deny" "$interval" "$unlock")
  face_auth_pam_row auth sufficient "pam_faillock.so ${fail_args}"
  face_auth_pam_row auth required "pam_deny.so"
  face_auth_pam_row account required "pam_unix.so"
  face_auth_pam_row account required "pam_faillock.so"
  face_auth_pam_row password required "pam_unix.so sha512 shadow"
  face_auth_pam_row session required "pam_unix.so"
}

face_auth_render_gate() {
  local policy="$1" cache
  cache=$(jq -r '.sudo_cache_seconds' <<<"$policy")
  cat <<EOF
#!/bin/bash
# Exit 0 only when face may be attempted. Any doubt exits 1 so PAM skips Howdy.
# sudo_cache_seconds=${cache} (ignored for hyprlock). Do not edit.
set -u
root=\${FACE_AUTH_ROOT:-}
state="\$root/run/omarchy-delight/face-auth"
service=\${1:-}
cache=${cache}

log() {
  if command -v logger >/dev/null 2>&1; then
    logger -t delight-face-auth -- "\$*" || true
  fi
}

deny() {
  log "deny service=\${service} reason=\$1"
  exit 1
}

case "\$service" in
  hyprlock | sudo) ;;
  *) deny "service" ;;
esac

if [[ -L \$state/password-ok ]]; then
  deny "password-stamp-symlink"
fi
if [[ ! -f \$state/password-ok ]]; then
  deny "no-password-since-boot"
fi
if [[ -e \$state/require-password ]]; then
  deny "suspend-or-policy"
fi

if [[ \$service == sudo ]]; then
  now=\$(date +%s) || deny "clock"
  mtime=\$(stat -c %Y -- "\$state/password-ok") || deny "password-stamp-unreadable"
  age=\$((now - mtime))
  if ((age < 0 || age > cache)); then
    deny "sudo-cache"
  fi
fi

log "allow service=\${service}"
exit 0
EOF
}

face_auth_render_stamp() {
  cat <<'EOF'
#!/bin/bash
# Record a password success and clear the suspend lockout.
# The PAM stack calls this only after pam_unix succeeds, never after face.
set -u
root=${FACE_AUTH_ROOT:-}
state="$root/run/omarchy-delight/face-auth"
service=${1:-password}
umask 077
mkdir -p -- "$state" || exit 1
chmod 0700 -- "$state" || exit 1
rm -f -- "$state/require-password"
date -u +%Y-%m-%dT%H:%M:%SZ >"$state/password-ok" || exit 1
chmod 0600 -- "$state/password-ok" || exit 1
if command -v logger >/dev/null 2>&1; then
  logger -t delight-face-auth -- "stamp service=${service} password-ok" || true
fi
exit 0
EOF
}

face_auth_render_sleep() {
  local policy="$1" limit
  limit=$(jq -r '.suspend_max_seconds' <<<"$policy")
  cat <<EOF
#!/bin/bash
# systemd-sleep hook. Exits 0 even on failure so it cannot block suspend.
# suspend_max_seconds=${limit}. 0 means every suspend, hibernate, or
# hybrid-sleep requires a password afterwards. Do not edit.
root=\${FACE_AUTH_ROOT:-}
state="\$root/run/omarchy-delight/face-auth"
limit=${limit}
phase=\${1:-}
kind=\${2:-}

mark() {
  umask 077
  mkdir -p -- "\$state" || return 1
  chmod 0700 -- "\$state" || return 1
  : >"\$state/require-password" || return 1
  chmod 0600 -- "\$state/require-password" || return 1
}

case "\$phase" in
  pre)
    umask 077
    mkdir -p -- "\$state" || exit 0
    chmod 0700 -- "\$state" || exit 0
    date +%s >"\$state/suspend-start" || rm -f -- "\$state/password-ok"
    exit 0
    ;;
  post) ;;
  *) exit 0 ;;
esac

case "\$kind" in
  suspend | hibernate | hybrid-sleep) ;;
  *) exit 0 ;;
esac

if ((limit == 0)); then
  mark || rm -f -- "\$state/password-ok"
  exit 0
fi

now=\$(date +%s) || {
  mark || rm -f -- "\$state/password-ok"
  exit 0
}
start=\$(cat -- "\$state/suspend-start" 2>/dev/null || true)
if [[ ! \$start =~ ^[0-9]+\$ ]] || ((now < start)) || ((now - start > limit)); then
  mark || rm -f -- "\$state/password-ok"
fi
exit 0
EOF
}

face_auth_render_disable() {
  cat <<'EOF'
#!/bin/bash
# One-command face-auth disable and PAM rollback. Safe to run twice.
# Does not need the delight CLI. From a text console:
#   sudo /usr/local/sbin/delight-face-auth-disable
# If this file is gone, restore /etc/pam.d from
# /var/lib/omarchy-delight/face-auth/backup using the manifest next to it.
# create: delete the path. replace: copy the backup back. See
# docs/face-auth-threat-model.md for the full break-glass procedure.
set -u
root=${FACE_AUTH_ROOT:-}
base="$root/var/lib/omarchy-delight/face-auth"
manifest="$base/manifest"

log() {
  if command -v logger >/dev/null 2>&1; then
    logger -t delight-face-auth -- "$*" || true
  fi
  printf 'delight-face-auth: %s\n' "$*" >&2
}

if [[ ! -f $manifest ]]; then
  log "already disabled (no manifest)"
  exit 0
fi

version=$(head -n 1 -- "$manifest" || true)
if [[ $version != v1 ]]; then
  log "refusing unknown manifest version"
  exit 1
fi

while IFS=$'\t' read -r path action backup || [[ -n ${path:-} ]]; do
  [[ -n ${path:-} ]] || continue
  [[ $path == \#* || $path == v1 ]] && continue
  dest="$root$path"
  case "$action" in
    create)
      rm -f -- "$dest"
      ;;
    replace)
      if [[ ! -f $base/backup/$backup ]]; then
        log "missing backup for $path"
        exit 1
      fi
      cp -f -- "$base/backup/$backup" "$dest"
      ;;
    *)
      log "bad manifest action for $path"
      exit 1
      ;;
  esac
done <"$manifest"

rm -f -- "$manifest"
rm -f -- \
  "$root/usr/local/lib/omarchy-delight/face-auth-gate" \
  "$root/usr/local/lib/omarchy-delight/face-auth-stamp" \
  "$root/usr/lib/systemd/system-sleep/omarchy-delight-face-auth"
log "face auth disabled; PAM restored"
exit 0
EOF
}

face_auth_render_recommendations() {
  local policy="$1" device
  device=$(jq -r '.device_path' <<<"$policy")
  cat <<EOF
Howdy Next recommendations (not installed over /etc/howdy/config.ini).
Invalid keys are rejected by \`howdy config\`. Change the camera with
\`sudo howdy config\` only after \`sudo howdy test\` works, and do not enable
PAM until then.

device_path: ${device:-<unset>}
Use a stable /dev/v4l/by-path/ or /dev/v4l/by-id/ node. Do not use /dev/videoN.
This policy rejects any other device_path shape.

Do not lower sface_threshold. The Howdy Next configuration guide says lowering
it makes matching easier and less strict. Raising it, if recognition is already
reliable, reduces false accepts. Leave yunet_score_threshold and the CLAHE /
dark_threshold knobs alone unless \`howdy test\` cannot see a face; those change
detection, not the password policy.

Do not enable capture of successful or failed frames if howdy.ini offers it.
A saved frame is a photo of whoever stood at the camera, stored on disk.

Enrolled templates must be root-owned, mode 0600, in a directory mode 0700,
with no symlinks. \`delight face-auth apply\` tightens the known template
directories when it can. It does not add a second encryption layer. At rest,
protection is the LUKS volume those directories sit on. Apply refuses to
install PAM when that mount does not look encrypted, unless
allow_unencrypted_models is true.
EOF
}

# Write every artifact for a normalised policy into dest/.
# Layout matches what apply installs, plus recommendations.txt.
face_auth_render_tree() {
  local policy="$1" dest="$2" service
  mkdir -p -- "$dest/pam.d" "$dest/lib" "$dest/sbin" "$dest/system-sleep"
  if [[ $(jq -r '.scope.hyprlock' <<<"$policy") == true ]]; then
    face_auth_render_pam hyprlock "$policy" >"$dest/pam.d/hyprlock"
  fi
  if [[ $(jq -r '.scope.sudo' <<<"$policy") == true ]]; then
    face_auth_render_pam sudo "$policy" >"$dest/pam.d/sudo"
  fi
  face_auth_render_gate "$policy" >"$dest/lib/face-auth-gate"
  face_auth_render_stamp >"$dest/lib/face-auth-stamp"
  face_auth_render_sleep "$policy" >"$dest/system-sleep/omarchy-delight-face-auth"
  face_auth_render_disable >"$dest/sbin/delight-face-auth-disable"
  face_auth_render_recommendations "$policy" >"$dest/recommendations.txt"
  chmod 0755 -- "$dest/lib/face-auth-gate" "$dest/lib/face-auth-stamp" \
    "$dest/sbin/delight-face-auth-disable" "$dest/system-sleep/omarchy-delight-face-auth"
  local rc=0
  for service in hyprlock sudo; do
    [[ -f $dest/pam.d/$service ]] || continue
    face_auth_validate_pam_file "$dest/pam.d/$service" "$policy" "$service" || rc=1
  done
  return "$rc"
}
